import { CAPABILITY_FAMILIES } from "./capability-catalog.js";
import { VERSION } from "./version.js";

/**
 * Shell completion generated from the same catalogue the CLI dispatches.
 *
 * The command list is the CLI's authoritative dispatch set, and the capability
 * descriptions come from the capability catalogue, so a command cannot exist
 * without appearing in completion and a removed command cannot linger. The
 * scripts only name commands and options; they never contact the engine, so a
 * completion never reveals whether a deployment is reachable or authorized.
 *
 * The marker line is what `scripts/uninstall.*` matches before deleting a file,
 * so an unrelated completion with the same name is never removed.
 */

export const COMPLETION_MARKER = "# coderax-cli shell completion";
export const SHELLS = Object.freeze(["bash", "zsh", "fish", "powershell"]);

const OPTION_WORDS = Object.freeze([
  "--json",
  "--help",
  "--version",
  "--base-url",
  "--token",
  "--token-file",
  "--with-token",
  "--timeout",
  "--out",
  "--force",
  "--task",
  "--file",
  "--question",
  "--no-wait",
  "--wait",
  "--wait-timeout",
  "--stream",
  "--agent",
  "--model",
  "--conversation",
  "--mode",
  "--at",
  "--every",
  "--interval-ms",
  "--start-at",
  "--reason",
  "--format",
  "--name",
  "--chart",
  "--size",
  "--count",
  "--voice",
  "--language",
  "--no-color",
  "--yes",
  "--dry-run",
  "--purge",
]);

function quote(value) {
  return String(value).replace(/'/g, "'\\''");
}

function zshQuote(value) {
  return String(value).replace(/'/g, "'\\''").replace(/:/g, "\\:");
}

function sorted(values) {
  return [...new Set(values)].sort();
}

function powershellScript(commandList) {
  const entries = commandList
    .map((command) => `    @{ Name = '${quote(command)}'; Description = 'coderax ${quote(command)}' }`)
    .join("\n");
  const flags = OPTION_WORDS.map(
    (flag) => `    @{ Name = '${quote(flag)}'; Description = 'option' }`,
  ).join("\n");
  return `# coderax ${VERSION} PowerShell completion
${COMPLETION_MARKER}
# Generated by \`coderax completion powershell\`. Load it from your profile:
#   . "$env:LOCALAPPDATA\\Coderax\\completions\\coderax.ps1"
Register-ArgumentCompleter -Native -CommandName coderax -ScriptBlock {
  param($wordToComplete, $commandAst, $cursorPosition)
  $commands = @(
${entries}
  )
  $flags = @(
${flags}
  )
  $elements = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })
  $firstArg = if ($elements.Count -ge 2) { $elements[1] } else { '' }
  $previous = if ($elements.Count -ge 1) { $elements[$elements.Count - 1] } else { '' }
  if ($flags.Name -contains $previous) { return }
  $candidates = if (-not $wordToComplete.StartsWith('-') -and $elements.Count -le 1) { $commands }
    elseif ($firstArg -eq 'config') { @('show', 'list', 'get', 'set') | ForEach-Object { @{ Name = $_; Description = 'config action' } } }
    elseif ($firstArg -eq 'completion') { @(${SHELLS.map((shell) => `'${shell}'`).join(", ")}) | ForEach-Object { @{ Name = $_; Description = 'shell' } } }
    elseif ($firstArg -eq 'call') { @('GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS') | ForEach-Object { @{ Name = $_; Description = 'HTTP method' } } }
    else { $flags }
  $candidates |
    Where-Object { $_.Name -like "$wordToComplete*" } |
    ForEach-Object {
      [System.Management.Automation.CompletionResult]::new($_.Name, $_.Name, 'ParameterValue', $_.Description)
    }
}
`;
}

export function completionScript(shell, commands) {
  const commandList = sorted(commands ?? []);
  const commandWords = commandList.join(" ");

  if (shell === "bash") {
    return `# coderax ${VERSION} bash completion
${COMPLETION_MARKER}
# Generated by \`coderax completion bash\`. Install:
#   coderax completion bash > "\${XDG_DATA_HOME:-$HOME/.local/share}/bash-completion/completions/coderax"
_coderax_complete() {
  local cur
  cur="\${COMP_WORDS[COMP_CWORD]}"
  if [ "$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=( $(compgen -W "${commandWords}" -- "$cur") )
    return 0
  fi
  COMPREPLY=( $(compgen -W "${OPTION_WORDS.join(" ")}" -- "$cur") )
  return 0
}
complete -F _coderax_complete coderax
`;
  }

  if (shell === "zsh") {
    const described = CAPABILITY_FAMILIES.filter((entry) => commandList.includes(entry.command))
      .map((entry) => `    '${zshQuote(entry.command)}:${zshQuote(entry.title)}'`)
      .join("\n");
    const plain = commandList
      .filter((command) => !CAPABILITY_FAMILIES.some((entry) => entry.command === command))
      .map((command) => `    '${zshQuote(command)}'`)
      .join("\n");
    return `#compdef coderax
${COMPLETION_MARKER}
# coderax ${VERSION} zsh completion
_coderax() {
  local -a commands
  commands=(
${[plain, described].filter(Boolean).join("\n")}
  )
  if (( CURRENT == 2 )); then
    _describe 'command' commands
    return
  fi
  _arguments '*: :->args'
}
_coderax "$@"
`;
  }

  if (shell === "fish") {
    const lines = commandList.map((command) => {
      const entry = CAPABILITY_FAMILIES.find((family) => family.command === command);
      const description = entry ? ` -d '${quote(entry.title)}'` : "";
      return `complete -c coderax -f -n "__fish_use_subcommand" -a "${quote(command)}"${description}`;
    });
    return `# coderax ${VERSION} fish completion
${COMPLETION_MARKER}
${lines.join("\n")}
complete -c coderax -f -n "not __fish_use_subcommand" -a "${OPTION_WORDS.join(" ")}"
`;
  }

  if (shell === "powershell") return powershellScript(commandList);

  throw Object.assign(new Error(`unsupported shell: ${String(shell)}`), { code: "USAGE" });
}
